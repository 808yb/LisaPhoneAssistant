-- 10. Atomic Booking RPC
CREATE OR REPLACE FUNCTION book_appointment_atomic(
  p_business_id UUID,
  p_customer_id BIGINT,
  p_title TEXT,
  p_start_time TIMESTAMPTZ,
  p_end_time TIMESTAMPTZ,
  p_notes TEXT,
  p_resource_id BIGINT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
  v_conflict_id UUID;
  v_new_appt_id UUID;
  v_result JSONB;
BEGIN
  -- Acquire transaction-level advisory lock to serialize booking requests
  IF p_resource_id IS NOT NULL THEN
     PERFORM pg_advisory_xact_lock(p_resource_id::integer);
  ELSE
     PERFORM pg_advisory_xact_lock(hashtext(p_business_id::text));
  END IF;

  -- 1. Check for overlapping time slots
  IF p_resource_id IS NOT NULL THEN
    SELECT id INTO v_conflict_id
    FROM public.appointments
    WHERE business_id = p_business_id
      AND resource_id = p_resource_id
      AND start_time < p_end_time
      AND end_time > p_start_time
    LIMIT 1;
  ELSE
    SELECT id INTO v_conflict_id
    FROM public.appointments
    WHERE business_id = p_business_id
      AND resource_id IS NULL
      AND start_time < p_end_time
      AND end_time > p_start_time
    LIMIT 1;
  END IF;

  -- 2. If conflict found, return error
  IF v_conflict_id IS NOT NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Der Zeitraum ist bereits belegt.');
  END IF;

  -- 3. Insert the appointment atomically
  INSERT INTO public.appointments (business_id, customer_id, title, start_time, end_time, notes, resource_id, status)
  VALUES (p_business_id, p_customer_id, p_title, p_start_time, p_end_time, p_notes, p_resource_id, 'confirmed')
  RETURNING id INTO v_new_appt_id;
  
  SELECT to_jsonb(a) INTO v_result FROM public.appointments a WHERE id = v_new_appt_id;

  RETURN jsonb_build_object('success', true, 'appointment', v_result);
END;
$$;