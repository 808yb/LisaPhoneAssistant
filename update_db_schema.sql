-- 3. RLS Helper Function
CREATE OR REPLACE FUNCTION public.auth_business_id()
RETURNS UUID
LANGUAGE sql STABLE
AS $$
  SELECT business_id FROM public.business_users WHERE user_id = auth.uid()
$$;

-- Helper function to check if user is superadmin
CREATE OR REPLACE FUNCTION public.is_superadmin()
RETURNS BOOLEAN
LANGUAGE sql STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.lisahq_admins WHERE email = (SELECT email FROM auth.users WHERE id = auth.uid())
  )
$$;

